# ============================================================
# 1. Load Libraries
# ============================================================

library(GEOquery)
library(Biobase)
library(tidyverse)


# ============================================================
# 2. Define Case Study Directory
# ============================================================

# The script belongs to:
#
# GSE25014_Microarray/scripts/
#
# Data generated by this case study will be stored inside:
#
# GSE25014_Microarray/data/
#
# GSE25014_Microarray/results/

case_study_dir <- "GSE25014_Microarray"


# Check whether the script is being executed from the
# repository root.

if (!dir.exists(case_study_dir)) {
  
  # If the case study directory does not exist,
  # assume the current working directory is already
  # GSE25014_Microarray.
  
  case_study_dir <- "."
  
}


# Display working case-study directory

cat("Case study directory:\n")
print(normalizePath(case_study_dir))


# ============================================================
# 3. Create Directory Structure
# ============================================================

raw_dir <- file.path(
  case_study_dir,
  "data",
  "raw",
  "GSE25014"
)

metadata_dir <- file.path(
  case_study_dir,
  "data",
  "metadata"
)

processed_dir <- file.path(
  case_study_dir,
  "data",
  "processed"
)

figures_dir <- file.path(
  case_study_dir,
  "figures"
)

results_dir <- file.path(
  case_study_dir,
  "results"
)


# Create directories

dir.create(
  raw_dir,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  metadata_dir,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  processed_dir,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  figures_dir,
  recursive = TRUE,
  showWarnings = FALSE
)

dir.create(
  results_dir,
  recursive = TRUE,
  showWarnings = FALSE
)


cat("\n✓ Project directories created.\n")


# ============================================================
# 4. Download GSE25014 from GEO
# ============================================================

cat("\n")
cat("============================================================\n")
cat("Downloading GSE25014 from GEO\n")
cat("============================================================\n")


# Download the GEO dataset.
#
# GSEMatrix = TRUE
# → download the processed expression matrix
#
# AnnotGPL = TRUE
# → include GPL annotation information
#
# getGPL = TRUE
# → retrieve the platform information

gse <- getGEO(
  GEO = "GSE25014",
  GSEMatrix = TRUE,
  AnnotGPL = TRUE,
  getGPL = TRUE
)


# ============================================================
# 5. Select the ExpressionSet
# ============================================================

# getGEO() can return a list when a GEO accession
# contains more than one platform.

if (is.list(gse)) {
  eset <- gse[[1]]
} else {
  eset <- gse
}


cat("\n✓ ExpressionSet successfully loaded.\n\n")


# Display the ExpressionSet
print(eset)


# ============================================================
# 6. Understand the ExpressionSet
# ============================================================

# An ExpressionSet is a Bioconductor object designed
# to organize high-throughput biological data.
#
# It contains several types of information.
#
#
# Expression data:
#
# exprs(eset)
#
#         ↓
#
# Probes × Samples
#
#
# Sample metadata:
#
# pData(eset)
#
#         ↓
#
# Samples × Variables
#
#
# Feature annotation:
#
# fData(eset)
#
#         ↓
#
# Probes × Annotation
#
# ============================================================


# ============================================================
# 7. Inspect Dataset Dimensions
# ============================================================

cat("\n")
cat("============================================================\n")
cat("Dataset Dimensions\n")
cat("============================================================\n")

dataset_dimensions <- dim(eset)
cat("Features (probes):", dataset_dimensions[1], "\n")
cat("Samples:", dataset_dimensions[2], "\n")


# ============================================================
# 8. Extract Expression Matrix
# ============================================================

expr_matrix <- exprs(eset)


cat("\n")
cat("Expression matrix dimensions:\n")

print(dim(expr_matrix))


cat("\nFirst rows of expression matrix:\n")

print(head(expr_matrix[, 1:5]))


# ============================================================
# 9. Inspect Expression Values
# ============================================================

cat("\n")
cat("Expression matrix class:\n")

print(class(expr_matrix))


cat("\nExpression summary:\n")

print(summary(as.vector(expr_matrix)))


# Check missing values
missing_values <- sum(is.na(expr_matrix))

cat("\nMissing values:", missing_values, "\n")


# ============================================================
# 10. Extract Sample Metadata
# ============================================================

pdata <- pData(eset)


# Convert to data frame

metadata <- pdata %>%
  as.data.frame() %>%
  rownames_to_column(
    var = "SampleID"
  )


cat("\n")
cat("============================================================\n")
cat("Sample Metadata\n")
cat("============================================================\n")


cat(  "\nMetadata dimensions:\n")

print(dim(metadata))


cat("\nMetadata columns:\n")

print(colnames(metadata))


cat("\nFirst samples:\n")

print(head(metadata))


# ============================================================
# 11. Inspect Sample Titles
# ============================================================

cat("\n")
cat("Sample titles:\n")

print(metadata$title)


# Display unique sample descriptions

cat("\n")
cat("Unique sample titles:\n")

print(unique(metadata$title))


# ============================================================
# 12. Extract Probe Annotation
# ============================================================

fdata <- fData(eset)


cat("\n")
cat("============================================================\n")
cat("Probe Annotation\n")
cat("============================================================\n")


cat("\nAnnotation dimensions:\n")

print(dim(fdata))


cat("\nAvailable annotation columns:\n")

print(colnames(fdata))


cat("\nFirst annotation records:\n")

print(head(fdata))


# ============================================================
# 13. Create Clean Annotation Table
# ============================================================

annotations <- fdata %>%
  as.data.frame() %>%
  rownames_to_column(
    var = "ProbeID"
  )


# Check whether expected annotation columns exist

if ("Gene symbol" %in% colnames(annotations)) {
  annotations <- annotations %>%
    select(
      ProbeID,
      `Gene symbol`,
      `Gene title`,
      everything()
    )
}


cat("\n")
cat("Clean annotation table:\n")

print(head(annotations))


# ============================================================
# 14. Count Probes with Gene Annotation
# ============================================================

if ("Gene symbol" %in% colnames(annotations)) {
  probes_with_symbol <- sum(
    !is.na(annotations$`Gene symbol`) &
      annotations$`Gene symbol` != ""
  )
} else {
  probes_with_symbol <- NA
}


cat("\nProbes with gene symbols:", probes_with_symbol, "\n")


# ============================================================
# 15. Inspect Platform Information
# ============================================================

cat("\n")
cat("============================================================\n")
cat("Platform Information\n")
cat("============================================================\n")


cat("\nPlatform:\n")

print(annotation(eset))


cat("\nOrganism:\n")

print(organism(eset))


# ============================================================
# 16. Save Expression Matrix
# ============================================================

write.csv(
  expr_matrix,
  file = file.path(
    raw_dir,
    "expr_matrix_rma.csv"
  )
)


cat(
  "\n✓ Expression matrix saved.\n"
)


# ============================================================
# 17. Save Sample Metadata
# ============================================================

write.csv(
  metadata,
  file = file.path(
    raw_dir,
    "metadata.csv"
  ),
  row.names = FALSE
)


cat(
  "✓ Sample metadata saved.\n"
)


# ============================================================
# 18. Save Probe Annotation
# ============================================================

write.csv(
  annotations,
  file = file.path(
    raw_dir,
    "probe_annotations.csv"
  ),
  row.names = FALSE
)


cat(
  "✓ Probe annotation saved.\n"
)


# ============================================================
# 19. Save ExpressionSet Object
# ============================================================

saveRDS(
