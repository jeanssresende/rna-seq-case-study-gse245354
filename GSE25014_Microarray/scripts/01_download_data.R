# ============================================================
# Thinking Like a Bioinformatician
# ============================================================
#
# A transcriptomic dataset is not just an expression matrix.
#
# In a microarray experiment, we need to understand at least
# three interconnected layers:
#
#
# 1. Expression
#
# Probe × Sample
#
#
# 2. Metadata
#
# Sample × Experimental variables
#
#
# 3. Annotation
#
# Probe × Biological information
#
#
# These three components will be connected throughout
# the following lessons.
#
#
# One of the main challenges of microarray analysis is:
#
#
#        PROBE
#          ↓
#      annotation
#          ↓
#         GENE
#
#
# A single gene can be represented by multiple probes.
#
# Therefore, before performing gene-level analyses,
# we need to understand how probes are mapped to genes
# and how multiple probes should be handled.
#
# This will be the focus of upcoming lessons.
#
# ============================================================


